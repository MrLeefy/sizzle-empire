export const GEAR_BY_ID: Record<string, GearTemplate> = Object.fromEntries(
  GEAR_TEMPLATES.map((g) => [g.id, g]),
);

export function getGearByRarityAndSource(
  rarity: Rarity,
  sourceFilter?: GearTemplate['source'] | GearTemplate['source'][],
): GearTemplate[] {
  return GEAR_TEMPLATES.filter((g) => {
    if (g.rarity !== rarity) return false;
    if (!sourceFilter) return true;
    if (Array.isArray(sourceFilter)) return sourceFilter.includes(g.source);
    return g.source === sourceFilter;
  });
}
